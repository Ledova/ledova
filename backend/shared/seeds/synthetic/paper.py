from contextlib import nullcontext
from uuid import uuid4

import pymupdf

from shared.seeds.synthetic.authority import historical_owner_appointment
from shared.seeds.synthetic.clock import frozen
from shared.seeds.synthetic.identities import slug
from tokens.models import RegisterEvidenceKind
from tokens.services.register_evidence import retain_register_evidence

SYNTHETIC_NOTICE = "Synthetic demonstration document generated by seed_demo. Not a real record."
PDF = "application/pdf"
RESOLUTION = "Directors' resolution"


def pdf(title, lines):
    with pymupdf.open() as document:
        page = document.new_page(width=595, height=842)
        page.insert_text((56, 72), title, fontsize=16)
        offset = 112
        for line in lines:
            page.insert_text((56, offset), line, fontsize=10)
            offset += 16
        page.insert_text((56, 800), SYNTHETIC_NOTICE, fontsize=8)
        return document.tobytes(no_new_id=True, garbage=3, deflate=True)


def acn_text(acn):
    return f"ACN {acn[:3]} {acn[3:6]} {acn[6:]}"


def _at(moment):
    return frozen(moment) if moment else nullcontext()


def evidence(company, kind, name, content, *, at=None):
    appointment = historical_owner_appointment(company)
    with _at(at):
        return retain_register_evidence(
            actor=company.owner,
            company_id=company.pk,
            appointment=appointment.pk,
            kind=kind,
            idempotency_key=uuid4(),
            name=name,
            raw=content,
            mime_type=PDF,
        )[0]


def authority(company, purpose, title, lines, *, at=None):
    content = pdf(f"{RESOLUTION}: {title}", [company.name, acn_text(company.acn), *lines])
    name = f"{slug(company.trading_name or company.name)}-{purpose}.pdf"
    return evidence(company, RegisterEvidenceKind.AUTHORITY, name, content, at=at)
